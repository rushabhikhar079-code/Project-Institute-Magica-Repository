                conditions.Add("r.RegNo = @RegNo");
                parameters.Add("RegNo", RegNo);
            }

            // Student name search (multiple name combinations)
            if (!string.IsNullOrEmpty(request.StudentName))
            {
                string studentName = request.StudentName.Replace(" ", "").Replace("'", "''").Trim();
                conditions.Add(@"(CONCAT_WS('',Salutation,fname, mname, lname) LIKE @StudentName
                    OR CONCAT_WS('',Salutation,fname,lname) LIKE @StudentName
                    OR CONCAT_WS('',Salutation,fname) LIKE @StudentName
                    OR CONCAT_WS('', fname, mname, lname) LIKE @StudentName
                    OR CONCAT_WS('',fname,lname) LIKE @StudentName)");
                parameters.Add("StudentName", $"%{studentName}%");
            }

            // Enquiry status filter
            if (request.EnqStatus.HasValue && request.EnqStatus.Value > 0)
            {
                conditions.Add("EnqStatus = @EnqStatus");
                parameters.Add("EnqStatus", request.EnqStatus.Value);
            }

            // Course filter
            if (!string.IsNullOrEmpty(request.CourseIds))
            {
                conditions.Add(@"r.RegNo IN (SELECT ss.StudID FROM student_subjects ss
                    WHERE ss.SubjectID IN (SELECT ts.subID FROM tbl_Subject ts
                    INNER JOIN tbl_Course tc ON ts.courseID=tc.courseID
                    WHERE ts.courseID IN (@CourseIds)))");
                parameters.Add("CourseIds", request.CourseIds);
            }

            // Subject filter
            if (!string.IsNullOrEmpty(request.SubjectIds))
            {
                conditions.Add(@"r.RegNo IN (SELECT ss.StudID FROM student_subjects ss
                    WHERE ss.SubjectID IN (@SubjectIds))");
                parameters.Add("SubjectIds", request.SubjectIds);
            }

            // Category filter
            if (request.Category == 1)
            {
                conditions.Add("r.Registered='no'");
            }
            else if (request.Category == 2)
            {
                conditions.Add("r.Registered='yes'");
            }

            // Date range filter based on category
            if (request.Category == 0 && !string.IsNullOrEmpty(request.FromDate) && !string.IsNullOrEmpty(request.ToDate))
            {
                DateTime fromDate = DateTime.Parse(request.FromDate);
                DateTime toDate = DateTime.Parse(request.ToDate);
                conditions.Add(@"((r.EnquiryDate BETWEEN @FromDate AND @ToDate)
                    OR (r.regDate BETWEEN @FromDate AND @ToDate))");
                parameters.Add("FromDate", fromDate.ToString("yyyy-MM-dd"));
                parameters.Add("ToDate", toDate.ToString("yyyy-MM-dd"));
            }
            else if (request.Category == 1 && !string.IsNullOrEmpty(request.FromDate) && !string.IsNullOrEmpty(request.ToDate))
            {
                DateTime fromDate = DateTime.Parse(request.FromDate);
                DateTime toDate = DateTime.Parse(request.ToDate);
                conditions.Add("r.EnquiryDate BETWEEN @FromDate AND @ToDate");
                parameters.Add("FromDate", fromDate.ToString("yyyy-MM-dd"));
                parameters.Add("ToDate", toDate.ToString("yyyy-MM-dd"));
            }
            else if (request.Category == 2 && !string.IsNullOrEmpty(request.FromDate) && !string.IsNullOrEmpty(request.ToDate))
            {
                DateTime fromDate = DateTime.Parse(request.FromDate);
                DateTime toDate = DateTime.Parse(request.ToDate);
                conditions.Add("r.regDate BETWEEN @FromDate AND @ToDate");
                parameters.Add("FromDate", fromDate.ToString("yyyy-MM-dd"));
                parameters.Add("ToDate", toDate.ToString("yyyy-MM-dd"));
            }

            // Build WHERE clause
            string whereClause = conditions.Any() ? " AND " + string.Join(" AND ", conditions) : "";

            // If Category is 3 (Pending Callback), use different query
            if (request.Category == 3)
            {
                return await GetPendingCallBackList(db, request, instituteId, branchId, userId, parameters, RegNo);
            }

            // Use GetStudentList query for Categories 0, 1, 2
            string query = string.Format(StudentQueries.GetStudentListBase, enquiryAllocateJoin + whereClause);
            string countQuery = string.Format(StudentQueries.GetStudentListCountBase, whereClause);

            // Add LEFT JOIN for enquiry status
            query = query.Replace("WHERE b.instituteid", "LEFT JOIN tblenquirystatus es ON (es.statusId=r.EnqStatus) WHERE b.instituteid");

            #region Sorting
            string direction =
                request.SortDirection?.Equals("desc", StringComparison.OrdinalIgnoreCase) == true
                    ? "DESC"
                    : "ASC";

            string orderByColumn;

            switch (request.SortBy)
            {
                case "EnquiryDate":
                    orderByColumn = "EDate";
                    break;
                case "Name":
                    orderByColumn = "NAME";
                    break;
                case "PContact":
                    orderByColumn = "pcontact";
                    break;
                case "CallBackDate":
                    orderByColumn = "CallBackDate";
                    break;
                case "FollowDate":
                    orderByColumn = "followdate";
                    break;
                case "RegNoManual":
                    orderByColumn = "regno_manual";
                    break;
                case "EnquiryStatus":
                    orderByColumn = "EnquiryStatus";
                    break;
                case "EnqStatus":
                    orderByColumn = "EnqStatus";
                    break;
                case "Registered":
                    orderByColumn = "Registered";
                    break;
                default:
                    orderByColumn = "r.regno";
                    break;
            }

            string orderByClause;

            if (!string.IsNullOrEmpty(request.SortBy))
            {
                orderByClause = $"ORDER BY {orderByColumn} {direction}, r.regno DESC";
            }
            else
            {
                orderByClause = "ORDER BY r.regno DESC, enquirydate DESC";
            }

            query = query + " " + orderByClause + " LIMIT @PageSize OFFSET @Offset";
            parameters.Add("PageSize", request.PageSize);
            parameters.Add("Offset", request.Offset);
            #endregion Sorting

            // Get total count
            var totalCount = await db.QueryFirstOrDefaultAsync<int>(countQuery, parameters);

            // Get paginated results
            var items = (await db.QueryAsync<EnquiryFollowUpListDto>(query, parameters)).ToList();

            return new PagedResponse<EnquiryFollowUpListDto>
            {
                Items = items,
                TotalCount = totalCount,
                PageNumber = request.PageNumber,
                PageSize = request.PageSize
            };
        }


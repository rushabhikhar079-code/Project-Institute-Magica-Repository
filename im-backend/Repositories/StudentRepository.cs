                await db.ExecuteAsync(
                    StudentQueries.DeleteStudentCourses,
                    new { RegNo = studentId },
                    transaction);

                // Delete student subjects
                await db.ExecuteAsync(
                    StudentQueries.DeleteStudentSubjects,
                    new { RegNo = studentId },
                    transaction);

                // Delete student other fees
                await db.ExecuteAsync(
                   StudentQueries.DeleteStudentOtherFees,
                   new { RegNo = studentId },
                   transaction);

                // Add student courses
                if (!string.IsNullOrEmpty(request.SelectedCourses))
                {
                    var courseIds = request.SelectedCourses.Split(',').Where(c => !string.IsNullOrWhiteSpace(c)).Select(int.Parse).ToList();
                    foreach (int courseId in courseIds)
                    {
                        await db.ExecuteAsync(
                            StudentQueries.InsertStudentCourse,
                            new { StudentId = studentId, CourseId = courseId },
                            transaction);
                    }
                }

                // Add student subjects
                if (!string.IsNullOrEmpty(request.SelectedSubjects))
                {
                    var subjectItems = request.SelectedSubjects.Split(',');
                    foreach (string item in subjectItems)
                    {
                        if (string.IsNullOrWhiteSpace(item)) continue;
                        var parts = item.Split('#');
                        int subjectId = int.Parse(parts[0]);
                        string feesType = parts.Length > 1 ? parts[1] : "";
                        DateTime subRegDate = parts.Length > 2 ? DateTime.Parse(parts[2]) : DateTime.Now;

                        // Insert subject
                        await db.ExecuteAsync(
                            StudentQueries.InsertStudentSubject,
                            new { StudId = studentId, SubjectId = subjectId, FeesType = feesType, SubRegDate = subRegDate },
                            transaction);

                        // Get subject details for fees calculation
                        var subjectDetails = await db.QueryFirstOrDefaultAsync<dynamic>(
                            StudentQueries.GetSubjectDetails,
                            new { SubjectId = subjectId },
                            transaction);

                        if (subjectDetails != null)
                        {
                            int durationSubType = Convert.ToInt32(subjectDetails.DurationSubType);
                            int noOfMonths = Convert.ToInt32(subjectDetails.NoofMonths);
                            double fees = Convert.ToDouble(subjectDetails.Fees);
                            bool allowProrated = Convert.ToBoolean(subjectDetails.Allow_prorated);

                            // Calculate monthly fees based on duration type
                            double monthlyFees = 0;
                            if (durationSubType == 1) // Monthly
                            {
                                monthlyFees = fees;
                            }
                            else if (durationSubType == 2) // Quarterly
                            {
                                monthlyFees = fees / 3;
                            }
                            else if (durationSubType == 3) // Half Yearly
                            {
                                monthlyFees = fees / 6;
                            }
                            else if (durationSubType == 4) // Yearly
                            {
                                monthlyFees = fees / 12;
                            }

                            // Generate monthly fees installments
                            for (int month = 0; month < noOfMonths; month++)
                            {
                                DateTime installmentDate = subRegDate.AddMonths(month);
                                int feeMonth = installmentDate.Month;
                                int feeYear = installmentDate.Year;

                                await db.ExecuteAsync(
                                    StudentQueries.InsertMonthlyFeesInstallment,
                                    new
                                    {
                                        StudentId = studentId,
                                        SubjectId = subjectId,
                                        FeeMonth = feeMonth,
                                        FeeYear = feeYear,
                                        BasicAmount = monthlyFees,
                                        BasicFees = fees
                                    },
                                    transaction);
                            }
                        }
                    }
                }

                // Add student other fees
                if (!string.IsNullOrEmpty(request.OtherFeesIds))
                {
                    var existingOtherFees = await db.QueryAsync<int>(
                        StudentQueries.CheckExistingOtherFees,
                        new { StudentId = studentId },
                        transaction);
                    var existingOtherFeesIds = existingOtherFees.ToList();

                    var otherFeesItems = request.OtherFeesIds.Split(',');
                    foreach (string ofCode in otherFeesItems)
                    {
                        if (string.IsNullOrWhiteSpace(ofCode)) continue;

                        if (!existingOtherFeesIds.Contains(int.Parse(ofCode)))
                        {
                            // Get other fees details
                            var otherFeesDetails = await db.QueryFirstOrDefaultAsync<dynamic>(
                                StudentQueries.GetOtherFeesDetails,
                                new { OfCode = ofCode },
                                transaction);

                            if (otherFeesDetails != null)
                            {
                                int frequency = Convert.ToInt32(otherFeesDetails.of_Frequency);
                                double amount = Convert.ToDouble(otherFeesDetails.amount);
                                int isTaxable = Convert.ToInt32(otherFeesDetails.istaxable);
                                int isIncluding = Convert.ToInt32(otherFeesDetails.isincluding);

                                if (frequency == 2) // Monthly - add 12 installments
                                {
                                    var regDateResult = await db.QueryFirstOrDefaultAsync<DateTime>(
                                        StudentQueries.GetStudentRegDate,
                                        new { StudentId = studentId },
                                        transaction);

                                    for (int month = 0; month <= 11; month++)
                                    {
                                        DateTime installmentDate = regDateResult.AddMonths(month);
                                        await db.ExecuteAsync(
                                            StudentQueries.InsertStudentOtherFees,
                                            new
                                            {
                                                StudentId = studentId,
                                                OfCode = ofCode,
                                                Amount = amount,
                                                IsTaxable = isTaxable,
                                                IsIncluding = isIncluding,
                                                Months = installmentDate.ToString("yyyy-MM-dd")
                                            },
                                            transaction);
                                    }
                                }
                                else // One-time
                                {
                                    await db.ExecuteAsync(
                                        StudentQueries.InsertStudentOtherFees,
                                        new
                                        {
                                            StudentId = studentId,
                                            OfCode = ofCode,
                                            Amount = amount,
                                            IsTaxable = isTaxable,
                                            IsIncluding = isIncluding,
                                            Months = string.Empty
                                        },
                                        transaction);
                                }
                            }
                        }
                    }
                }

                // Update education
                await db.ExecuteAsync(
                    StudentQueries.DeleteEducationDetails,
                    new { RegNo = studentId },
                    transaction);

                var tempEducation = await db.QueryAsync<dynamic>(
                    "SELECT * FROM temp_education",
                    transaction: transaction);

                foreach (var edu in tempEducation)
                {
                    await db.ExecuteAsync(
                        StudentQueries.InsertEducationDetail,
                        new
                        {
                            Degree = edu.Degree,
                            CollegeName = edu.CollegeName,
                            Stream = edu.Stream,
                            Percentage = edu.Percentage,
                            Year = edu.Year1,
                            RegNo = studentId
                        },
                        transaction);
                }

                // Delete temp education after use
                await db.ExecuteAsync(StudentQueries.DeleteTempEducation, transaction: transaction);

                // Delete and add batch details
                await db.ExecuteAsync(
                    StudentQueries.DeleteEnquiryBatchDetails,
                    new { RegNo = studentId },
                    transaction);

                foreach (int batchId in request.BatchIds)
                {
                    await db.ExecuteAsync(
                        StudentQueries.InsertEnquiryBatchDetails,
                        new { RegNo = studentId, BatchId = batchId, InstId = instituteId, BranchId = request.BranchId },
                        transaction);
                }

                // Handle follow-up remarks
                if (request.EnableFollowUp)
                {
                    DateTime callDate = DateTime.Now;
                    string time = callDate.ToString("HH:mm");

                    await db.ExecuteAsync(
                        StudentQueries.InsertFollowUpRemark,
                        new
                        {
                            StudId = studentId.ToString(),
                            StatusId = request.FollowUpStatusId ?? 0,
                            CallDate = callDate.ToString("yyyy-MM-dd HH:mm"),
                            Remarks = request.FollowUpRemarks,
                            CalledBy = userId.ToString(),
                            Interested = request.IsInterested ? 1 : 0,
                            InstId = instituteId,
                            BranchId = request.BranchId,
                            CallbackDate = request.FollowUpDate,
                            UserId = userId,
                            Time = time
                        },
                        transaction);

                    // Update follow-up date in registration
                    await db.ExecuteAsync(
                        StudentQueries.UpdateFollowUpDate,
                        new
                        {
                            RegNo = studentId.ToString(),
                            BranchId = request.BranchId,
                            FollowUpDate = request.FollowUpDate,
                            Remarks = request.FollowUpRemarks
                        },
                        transaction);
                }

                transaction.Commit();

                return (true, "Enquiry updated successfully", studentId);
            }
            catch (Exception ex)
            {
                transaction.Rollback();
                return (false, $"Error updating enquiry: {ex.Message}", null);
            }
        }

        public async Task<PagedResponse<EnquiryFollowUpListDto>> SearchEnquiryFollowUpAsync(EnquiryFollowUpSearchDto request, int instituteId, int branchId, string? userId = null, int? RegNo = 0)

                                }
                            }
                            else
                            {
                                await db.ExecuteAsync(StudentQueries.InsertStudentOtherFees,
                                    new
                                    {
                                        StudentId = studentId,
                                        OfCode = ofCode,
                                        Amount = amount,
                                        IsTaxable = isTaxable,
                                        IsIncluding = isIncluding
                                    },
                                    transaction);
                            }
                        }
                    }
                }

                // Update education
                await db.ExecuteAsync(StudentQueries.DeleteEducation,
                    new { RegNo = studentId },
                    transaction);

                if (request.Education.Any())
                {
                    foreach (var edu in request.Education)
                    {

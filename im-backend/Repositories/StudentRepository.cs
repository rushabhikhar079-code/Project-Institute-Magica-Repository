        public async Task<(bool Success, string Message)> BulkUpdateStudentStatusAsync(BulkStudentStatusDto request, int instituteId)
        {
            using IDbConnection db = _dbFactory.CreateConnection();
            if (db.State == ConnectionState.Closed)
                db.Open();

            using var transaction = db.BeginTransaction();
            try
            {
                // Validate inputs
                if (request.StudentIds == null || request.StudentIds.Count == 0)
                    return (false, "Please select at least one student.");

                if (request.Status != 0 && request.Status != 1)
                    return (false, "Invalid status. Status must be 0 (Inactive) or 1 (Active).");

                // If setting to inactive, require InactiveStatus
                if (request.Status == 0 && string.IsNullOrEmpty(request.InactiveStatus))
                    return (false, "Inactive status reason is required when deactivating students.");

                // Update each student
                foreach (int studentId in request.StudentIds)
                {
                    if (request.Status == 1)
                    {
                        // Active: set StatusFlag = 1, InactiveStatus = NULL
                        await db.ExecuteAsync(
                            StudentQueries.UpdateStudentStatusActive,
                            new { Status = request.Status, StudentId = studentId },
                            transaction);
                    }
                    else
                    {
                        // Inactive: set StatusFlag = 0, InactiveStatus = provided reason
                        await db.ExecuteAsync(
                            StudentQueries.UpdateStudentStatusInactive,
                            new { Status = request.Status, InactiveStatus = request.InactiveStatus, StudentId = studentId },
                            transaction);
                    }
                }

                transaction.Commit();
                return (true, $"Successfully updated {request.StudentIds.Count} student(s).");
            }
            catch (Exception ex)
            {
                transaction.Rollback();
                return (false, $"Error updating student status: {ex.Message}");

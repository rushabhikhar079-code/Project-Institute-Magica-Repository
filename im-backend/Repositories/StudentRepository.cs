                if (userExist == 1)
                {
                    await SendEditNotificationsAsync(db, instituteId, branchId, studentId, request, username, password);
                }

                return (true, "Student updated successfully", studentId);
            }
            catch (Exception ex)
            {
                transaction.Rollback();
                return (false, $"Error updating student: {ex.Message}", null);
            }
        }


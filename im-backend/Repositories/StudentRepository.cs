        public async Task<PagedResponse<EnquiryAllocationListDto>> SearchEnquiryAllocationAsync(EnquiryAllocationSearchDto request, int instituteId, string? userId = null)
        {
            using IDbConnection db = _dbFactory.CreateConnection();
            if (db.State == ConnectionState.Closed)
                db.Open();

            try
            {
                var conditions = new List<string>();
                var parameters = new DynamicParameters();
                string str = " WHERE r.statusflag=1 and r.branchId=" + request.BranchId.ToString();
                string str1 = string.Empty;

                // Set GetSFlag based on Category
                // Category: 0=All, 1=Enquiry, 2=Registration
                string getSFlag = "";
                switch (request.Category)
                {
                    case 1: // Enquiry
                        getSFlag = "No";
                        break;
                    case 2: // Registration
                        getSFlag = "Yes";
                        break;
                    case 0: // All - no filter
                    default:
                        getSFlag = "";
                        break;
                }

                // Enquiry Status filter
                if (request.EnqStatus.HasValue && request.EnqStatus.Value > 0)
                {
                    str = str + " AND r.EnqStatus=" + request.EnqStatus.Value.ToString();
                }

                // Date range filter
                if (!string.IsNullOrEmpty(request.FromDate) && !string.IsNullOrEmpty(request.ToDate))
                {
                    if (getSFlag == "No")
                    {
                        str = str + " and r.EnquiryDate between '" + DateTime.Parse(request.FromDate).ToString("yyyy-MM-dd") + "' and '" + DateTime.Parse(request.ToDate).ToString("yyyy-MM-dd") + "'" + " or  (DATE(ea.alctdate) BETWEEN '" + DateTime.Parse(request.FromDate).ToString("yyyy-MM-dd") + "' AND '" + DateTime.Parse(request.ToDate).ToString("yyyy-MM-dd") + "')";
                    }
                    else
                    {
                        str = str + " and r.RegDate between '" + DateTime.Parse(request.FromDate).ToString("yyyy-MM-dd") + "' and '" + DateTime.Parse(request.ToDate).ToString("yyyy-MM-dd") + "'" + " or  (DATE(ea.alctdate) BETWEEN '" + DateTime.Parse(request.FromDate).ToString("yyyy-MM-dd") + "' AND '" + DateTime.Parse(request.ToDate).ToString("yyyy-MM-dd") + "')";
                    }
                }
                else
                {
                    if (!string.IsNullOrEmpty(request.FromDate))
                        str = str + " and r.EnquiryDate='" + DateTime.Parse(request.FromDate).ToString("yyyy-MM-dd") + "'" + " and (DATE(ea.alctdate) BETWEEN '" + DateTime.Parse(request.FromDate).ToString("yyyy-MM-dd") + "'";
                    if (!string.IsNullOrEmpty(request.ToDate))
                        str = str + " and r.EnquiryDate='" + DateTime.Parse(request.ToDate).ToString("yyyy-MM-dd") + "'" + " and  (DATE(ea.alctdate) BETWEEN '" + DateTime.Parse(request.ToDate).ToString("yyyy-MM-dd") + "'";
                    if (!string.IsNullOrEmpty(getSFlag))
                        str = str + " and r.registered='" + getSFlag + "'";
                }

                // User filter
                if (request.CheckUser)
                {
                    if (!string.IsNullOrEmpty(request.UserId) && request.UserId != "0")
                        str = str + " and u.user_Id= " + request.UserId;
                    str += " and r.RegNo in (Select regno from enquiryallocate)";
                }             

                // Subject filter
                if (!string.IsNullOrEmpty(request.SubjectIds))
                    str = str + " and s.SubjectId in (" + request.SubjectIds + ")";

                // Build the LEFT JOIN condition for registered flag
                string registeredJoinCondition = !string.IsNullOrEmpty(getSFlag) ? "and r.registered='" + getSFlag + "'" : "";

                // Build the UNION query using StudentQueries
                string query = string.Format(StudentQueries.SearchEnquiryAllocation, registeredJoinCondition, str, str + str1);

                // Execute query
                var items = await db.QueryAsync<EnquiryAllocationListDto>(query);

                // Apply pagination in memory
                int totalCount = items.Count();
                var pagedItems = items
                    .Skip((request.PageNumber - 1) * request.PageSize)
                    .Take(request.PageSize)
                    .ToList();

                return new PagedResponse<EnquiryAllocationListDto>
                {
                    Items = pagedItems,
                    TotalCount = totalCount,
                    PageNumber = request.PageNumber,
                    PageSize = request.PageSize
                };
            }
            catch (Exception ex)
            {
                return new PagedResponse<EnquiryAllocationListDto>
                {
                    Items = new List<EnquiryAllocationListDto>(),
                    TotalCount = 0,
                    PageNumber = request.PageNumber,
                    PageSize = request.PageSize
                };
            }
        }
        public async Task<AutoRegNoDto> GetAutoRegNoAsync(int instituteId, int branchId)
        {
            using IDbConnection db = _dbFactory.CreateConnection();

            if (db.State == ConnectionState.Closed)
                db.Open();

            // 1. Try branch-level configuration.
            var config = await db.QueryFirstOrDefaultAsync<AutoRegNoDto>(
                StudentQueries.GetAutoRegNo,
                new
                {
                    InstId = instituteId,
                    BranchId = branchId
                });

            bool isInstituteLevel = false;

            // 2. Fall back to institute-level configuration.
            if (config == null || config.CurrentRegNo == null)
            {
                config = await db.QueryFirstOrDefaultAsync<AutoRegNoDto>(
                    StudentQueries.GetAutoRegNo,
                    new
                    {
                        InstId = instituteId,
                        BranchId = 0
                    });

                isInstituteLevel = true;
            }

            // 3. No configuration found.
            if (config == null || config.CurrentRegNo == null)
            {
                return new AutoRegNoDto
                {
                    RegistrationNo = string.Empty,
                    SystemGen = true,
                    TempRegNo = null,
                    RegLevel = 0,
                    Automated = 0,
                    ShowRegNoCheckbox = false,
                    RegNoCheckboxChecked = false,
                    RegNoCheckboxEnabled = false,
                    RegNoEnabled = true
                };
            }

            // 4. Automated registration is disabled.
            if (config.Automated != 0)
            {
                return new AutoRegNoDto
                {
                    RegistrationNo = string.Empty,
                    SystemGen = false,
                    RegLevel = config.RegLevel,
                    Automated = config.Automated,
                    RegFormat = config.RegFormat,
                    ShowRegNoCheckbox = true,
                    RegNoCheckboxChecked = true,
                    RegNoCheckboxEnabled = false,
                    RegNoEnabled = true
                };
            }

            int currentRegNo = config.CurrentRegNo.Value;

            var result = new AutoRegNoDto
            {
                SystemGen = false,
                RegLevel = config.RegLevel,
                Automated = config.Automated,
                RegFormat = config.RegFormat,
                ShowRegNoCheckbox = false,
                RegNoCheckboxChecked = false,
                RegNoCheckboxEnabled = false,
                RegNoEnabled = true
            };

            // 5. Numeric registration number.
            if (config.RegFormat == 0)
            {
                result.RegistrationNo = (currentRegNo + 1).ToString();
            }
            // 6. Prefix-based registration number.
            else if (
                config.RegFormat == 1 ||
                config.RegFormat == 2 ||
                (!isInstituteLevel && config.RegFormat == 3))
            {
                result.RegistrationNo =
                    $"{config.Prefix}/{currentRegNo}";

                result.TempRegNo = currentRegNo + 1;
            }
            // 7. Manual registration number.
            else
            {
                int nextRegNo = await GetNextAvailableManualRegNoAsync(
                    db,
                    branchId,
                    "0");

                result.RegistrationNo = nextRegNo.ToString();
                result.SystemGen = true;
            }

            return result;
        }

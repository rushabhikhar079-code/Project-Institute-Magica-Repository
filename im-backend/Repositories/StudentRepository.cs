{
    public class StudentRepository : IStudentRepository
    {
        private readonly IDbConnectionFactory _dbFactory;
        private readonly IEmailService _emailService;
        private readonly ISMSService _smsService;
        private readonly IWhatsAppService _whatsappService;

        public StudentRepository(IDbConnectionFactory dbFactory, IEmailService emailService, ISMSService smsService, IWhatsAppService whatsappService)
        {
            _dbFactory = dbFactory;
            _emailService = emailService;
            _smsService = smsService;
            _whatsappService = whatsappService;
        }

        public async Task<(bool Success, string Message, int? StudentId, string? RegNo)> RegisterStudentAsync(StudentRegistrationDto request, int instituteId, int branchId, int userId, string ipAddress)
        {
            using IDbConnection db = _dbFactory.CreateConnection();
            if (db.State == ConnectionState.Closed)
                db.Open();
            using var transaction = db.BeginTransaction();

            try
            {
                // Delete temp education records before registration
                await db.ExecuteAsync(StudentQueries.DeleteTempEducation, transaction: transaction);

                // Get registration number format settings
                var regNoFormat = await db.QueryFirstOrDefaultAsync<dynamic>(
                    StudentQueries.GetRegNoFormat,
                    new { InstituteId = instituteId, BranchId = branchId },
                    transaction);

                bool isAutoGenerated = false;
                int regLevel = 0;
                int? tempRegNo = null;
                string generatedRegNo = request.RegNo;

                if (regNoFormat != null)
                {
                    int automated = regNoFormat.automated ?? 0;
                    int autoRegNo = Convert.ToInt32(regNoFormat.autoregno ?? 0);
                    string regPrefix = regNoFormat.regprefix ?? string.Empty;
                    int regFormatType =Convert.ToInt32(regNoFormat.regformattype ?? 0);
                    regLevel = Convert.ToInt32(regNoFormat.reglevel ?? 0);

                    // If automated is 0, generate auto registration number
                    if (automated == 0)
                    {
                        isAutoGenerated = true;
                        int nextCounter = autoRegNo + 1;

                        if (regFormatType == 1 || regFormatType == 2 || regFormatType == 3)
                        {
                            // Format: prefix/counter
                            generatedRegNo = regPrefix + "/" + nextCounter.ToString();
                        }
                        else if (regFormatType == 0)
                        {
                            // Format: counter only
                            generatedRegNo = nextCounter.ToString();
                        }
                        else
                        {
                            // Manual - use provided RegNo
                            isAutoGenerated = false;
                            generatedRegNo = request.RegNo;
                        }

                        if (isAutoGenerated)
                        {
                            tempRegNo = nextCounter;
                        }
                    }
                    else
                    {
                        // Manual - use provided RegNo
                        isAutoGenerated = false;
                        generatedRegNo = request.RegNo;
                    }
                }
                else
                {
                    // No format found - use provided RegNo
                    isAutoGenerated = false;
                    generatedRegNo = request.RegNo;
                }

                // Use generated or provided registration number
                request.RegNo = generatedRegNo;

                // Validate registration date - not future date
                DateTime regDate;
                if (!DateTime.TryParse(request.RegDate, out regDate))
                {
                    return (false, "Invalid registration date format. Please use dd/MM/yyyy format.", null, null);
                }

                if (regDate > DateTime.Now)
                {
                    return (false, "Registration date cannot be a future date.", null, null);
                }

                // Validate date of birth
                DateTime? dob = null;
                if (!string.IsNullOrEmpty(request.DateOfBirth))
                {
                    if (!DateTime.TryParse(request.DateOfBirth, out DateTime parsedDob))
                    {
                        return (false, "Invalid date of birth format. Please use dd/MM/yyyy format.", null, null);
                    }
                    if (parsedDob >= DateTime.Today)
                    {
                        return (false, "Date of birth must be less than today's date.", null, null);
                    }
                    dob = parsedDob;
                }

                // Validate photo size (max 2MB)
                if (request.Photo != null && request.Photo.Length > 2097152)
                {
                    return (false, "Please select image file upto 2MB.", null, null);
                }

                // Check student limit for new registrations
                var instituteLimit = await db.QueryFirstOrDefaultAsync<dynamic>(
                    StudentQueries.CheckInstituteStudentLimit,
                    new { InstituteId = instituteId });

                if (instituteLimit != null)
                {
                    int? regCount = (int?)instituteLimit.regcount ?? 0;
                    bool isBranchwise = instituteLimit.IsBranchwise ?? 0;
                    int? regType = (int?)instituteLimit.regtype ?? 0;
                    int? noOfReg = (int?)instituteLimit.noofreg ?? 0;

                    // Check current plan
                    string currentDate = DateTime.Now.ToString("yyyy-MM-dd");
                    var plan = await db.QueryFirstOrDefaultAsync<dynamic>(
                        StudentQueries.CheckCurrentPlanExpiry,
                        new { InstituteId = instituteId, CurrentDate = currentDate });

                    if (plan != null && isBranchwise == false) // Student Wise
                    {
                        int noOfStudents = plan.noofstudents ?? 0;
                        if (regCount >= noOfStudents)
                        {
                            return (false, $"You have subscribed for {noOfStudents} students, the maximum limit for students should not exceed (Registration-{noOfStudents}). For more details please contact Techior Solutions Pvt. Ltd. at 9766616435.", null, null);
                        }
                    }
                    else if (plan == null && isBranchwise == false) // Student Wise without plan
                    {
                        if (regCount >= noOfReg)
                        {
                            if (regType == 0) // Trial Institute
                                return (false, "Trial user cannot add more than 10 registrations.", null, null);
                            else
                                return (false, $"No. of total students cannot exceed {noOfReg}. Please contact Techior Solutions Pvt. Ltd. at 9766616435.", null, null);
                        }
                    }
                    else if (plan == null && isBranchwise == true && regType == 0) // Branchwise Trial
                    {
                        if (regCount >= 10)
                        {
                            return (false, "Trial user cannot add more than 10 registrations.", null, null);
                        }
                    }
                }

                // Check duplicate student
                int duplicateCount = await db.QueryFirstOrDefaultAsync<int>(
                    StudentQueries.CheckDuplicateStudent,
                    new
                    {
                        FirstName = request.FirstName.Replace("'", "''"),
                        LastName = request.LastName.Replace("'", "''"),
                        Mobile = request.Mobile,
                        BranchId = branchId,
                        StudentId = 0
                    },
                    transaction);

                if (duplicateCount > 0)
                {
                    return (false, "The student with the same information already exists.", null, null);
                }

                // Check duplicate registration number
                int duplicateRegNo = await db.QueryFirstOrDefaultAsync<int>(
                    StudentQueries.CheckDuplicateRegNo,
                    new { RegNo = request.RegNo, BranchId = branchId, RegId = 0 },
                    transaction);

                if (duplicateRegNo > 0)
                {
                    return (false, $"Registration number ({request.RegNo}) is already assigned.", null, null);
                }

                // Check duplicate biometric ID
                if (!string.IsNullOrEmpty(request.BiometricAttendanceId))
                {
                    string regCondition = string.Empty;
                    string trainerCondition = string.Empty;

                    var result = await db.QueryFirstOrDefaultAsync<dynamic>(
                        string.Format(StudentQueries.CheckDuplicateBiometricId, regCondition, trainerCondition),
                        new { BiometricAttendanceId = request.BiometricAttendanceId, BranchId = branchId },
                        transaction);

                    if (result != null)
                    {
                        return (false, "Biometric attendance ID already exists.", null, null);
                    }
                }

                // Check duplicate roll number
                if (!string.IsNullOrWhiteSpace(request.RollNo))
                {
                    int duplicateRollNo = await db.QueryFirstOrDefaultAsync<int>(
                        StudentQueries.CheckDuplicateRollNo,
                        new
                        {
                            RollNo = request.RollNo,
                            BranchId = branchId,
                            StudentId = 0
                        },
                        transaction);

                    if (duplicateRollNo > 0)
                    {
                        return (false, "Roll number already exists.", null, null);
                    }
                }

                // Generate username and password
                string username = null;
                string password = null;

                if (string.IsNullOrEmpty(username) || string.IsNullOrEmpty(password))
                {
                    int suffix = 0;
                    string generatedUsername;
                    string generatedPassword;

                    do
                    {
                        if (suffix == 0)
                        {
                            if (!string.IsNullOrEmpty(request.MiddleName) && !string.IsNullOrEmpty(request.LastName))
                            {
                                generatedUsername = request.FirstName.Substring(0, 1) + request.MiddleName.Substring(0, 1) + request.LastName;
                                generatedPassword = request.FirstName.Substring(0, 1) + request.MiddleName.Substring(0, 1) + request.LastName + (dob.HasValue ? dob.Value.ToString("dd") : "01");
                            }
                            else if (string.IsNullOrEmpty(request.MiddleName) && !string.IsNullOrEmpty(request.LastName))
                            {
                                generatedUsername = request.FirstName.Substring(0, 1) + request.LastName;
                                generatedPassword = request.FirstName.Substring(0, 1) + request.LastName + (dob.HasValue ? dob.Value.ToString("dd") : "01");
                            }
                            else
                            {
                                generatedUsername = request.FirstName;
                                generatedPassword = request.FirstName + (dob.HasValue ? dob.Value.ToString("dd") : "01");
                            }
                        }
                        else
                        {
                            if (!string.IsNullOrEmpty(request.MiddleName) && !string.IsNullOrEmpty(request.LastName))
                            {
                                generatedUsername = request.FirstName.Substring(0, 1) + request.MiddleName.Substring(0, 1) + request.LastName + suffix;
                                generatedPassword = request.FirstName.Substring(0, 1) + request.MiddleName.Substring(0, 1) + request.LastName + (dob.HasValue ? dob.Value.ToString("dd") : "01") + suffix;
                            }
                            else if (string.IsNullOrEmpty(request.MiddleName) && !string.IsNullOrEmpty(request.LastName))
                            {
                                generatedUsername = request.FirstName.Substring(0, 1) + request.LastName + suffix;
                                generatedPassword = request.FirstName.Substring(0, 1) + request.LastName + (dob.HasValue ? dob.Value.ToString("dd") : "01") + suffix;
                            }
                            else
                            {
                                generatedUsername = request.FirstName + suffix;
                                generatedPassword = request.FirstName + (dob.HasValue ? dob.Value.ToString("dd") : "01") + suffix;
                            }
                        }

                        int userCount = await db.QueryFirstOrDefaultAsync<int>(
                            StudentQueries.CheckUser,
                            new { Username = generatedUsername },
                            transaction);

                        if (userCount > 0)
                        {
                            suffix++;
                        }
                        else
                        {
                            username = generatedUsername;
                            password = generatedPassword;
                        }
                    } while (string.IsNullOrEmpty(username));
                }

                // Insert student
                int studentId = await db.QueryFirstOrDefaultAsync<int>(
                     StudentQueries.InsertStudent,
                     new
                     {
                         RegDate = regDate,
                         EnquiryDate = (DateTime?)null,
                         FirstName = request.FirstName.Replace("'", "''"),
                         MiddleName = request.MiddleName.Replace("'", "''"),
                         LastName = request.LastName.Replace("'", "''"),
                         Address = request.Address.Replace("'", "''"),
                         PermanentAddress = request.PermanentAddress?.Replace("'", "''"),
                         FatherFirstName = request.FatherFirstName.Replace("'", "''"),
                         FatherMiddleName = request.FatherMiddleName?.Replace("'", "''"),
                         FatherLastName = request.FatherLastName?.Replace("'", "''"),
                         Occupation = request.Occupation,
                         Organization = request.Organization,
                         PContact = request.Mobile,
                         Mobile1 = request.Mobile1,
                         Mobile2 = request.Mobile2,
                         Email = request.Email,
                         DOB = dob,
                         WorkStatus = request.WorkStatus,
                         Company = request.ParentCompanyName,
                         Comments = request.Comments,
                         Source = request.Source,
                         HomePhone = request.HomePhone,
                         Salary = request.Salary ?? 0,
                         FollowUpDate = (DateTime?)null,
                         Registered = "Yes",
                         BranchId = branchId,
                         City = request.CityId,
                         State = request.StateId,
                         CityC = request.CityIdC,
                         StateC = request.StateIdC,
                         PinCode = request.PinCode,
                         PinCodeC = request.PinCodeC,
                         RegNo = request.RegNo,
                         Category = request.Category,
                         Username = username,
                         Password = password,
                         District = "",
                         DistrictC = "",
                         WalkIn = "",
                         WalkInDate = (DateTime?)null,
                         CountryIdC = request.CountryIdC,
                         StateIdC = request.StateIdC,
                         CityIdC = request.CityIdC,
                         OtherCityC = request.OtherCityC,
                         CountryId = request.CountryId,
                         StateId = request.StateId,
                         CityId = request.CityId,
                         OtherCity = request.OtherCity,
                         BiometricAttendanceId = request.BiometricAttendanceId,
                         Remarks = request.Remarks,
                         EnqStatus = 0,
                         Gender = request.Gender,
                         Salutation = request.Salutation,
                         ParentCompanyName = request.ParentCompanyName,
                         ParentGSTNo = request.ParentGSTNo,
                         UserId = userId,
                         RollNo = string.IsNullOrWhiteSpace(request.RollNo) ? null : request.RollNo,
                         Age = request.Age ?? 0
                     },
                     transaction);

                // Update auto registration counter if RegNo was auto-generated
                if (isAutoGenerated && tempRegNo.HasValue)
                {
                    int targetBranchId = regLevel == 0 ? 0 : branchId;
                    await db.ExecuteAsync(
                        StudentQueries.UpdateAutoRegCounter,
                        new { InstituteId = instituteId, BranchId = targetBranchId, NewCounter = tempRegNo.Value },
                        transaction);
                }

                // Insert student courses
                if (!string.IsNullOrEmpty(request.SelectedCourses))
                {
                    var courseIds = request.SelectedCourses.Split(',');
                    foreach (var courseIdStr in courseIds)
                    {
                        if (int.TryParse(courseIdStr.Trim(), out int courseId))
                        {
                            await db.ExecuteAsync(
                                StudentQueries.InsertStudentCourse,
                                new
                                {
                                    StudentId = studentId,
                                    CourseId = courseId
                                },
                                transaction);
                        }
                    }
                }

                // Insert student subjects with monthly fees installment logic
                if (!string.IsNullOrEmpty(request.SelectedSubjects))
                {
                    // Format: SubjectID#FeesType#SubRegDate
                    var subjectData = request.SelectedSubjects.Split(',');
                    var existingSubjects = await db.QueryAsync<int>(
                        StudentQueries.CheckExistingSubject,
                        new { StudentId = studentId },
                        transaction);

                    foreach (var subjectItem in subjectData)
                    {
                        var parts = subjectItem.Split('#');
                        if (parts.Length >= 3 && int.TryParse(parts[0].Trim(), out int subjectId))
                        {
                            // Check if subject already exists
                            if (!existingSubjects.Contains(subjectId))
                            {
                                string feesType = parts[1].Trim();
                                DateTime subRegDate = DateTime.TryParse(parts[2].Trim(), out DateTime parsedDate) ? parsedDate : regDate;

                                // Insert subject
                                await db.ExecuteAsync(
                                    StudentQueries.InsertStudentSubjects,
                                    new
                                    {
                                        StudentId = studentId,
                                        SubjectId = subjectId,
                                        FeesType = feesType,
                                        SubRegDate = subRegDate
                                    },
                                    transaction);

                                // Get subject details for monthly fees
                                var subjectDetails = await db.QueryFirstOrDefaultAsync<dynamic>(
                                    StudentQueries.GetSubjectDetails,
                                    new { SubjectId = subjectId },
                                    transaction);

                                if (subjectDetails != null)
                                {
                                    int durationSubType = subjectDetails.DurationSubType ? 1 : 0;
                                    int noOfMonths = (int?)subjectDetails.NoofMonths ?? 0;
                                    DateTime? courseEndDate = subjectDetails.CourseEndDate as DateTime?;
                                    double fees = subjectDetails.Fees ?? 0;
                                    int allowProrated = (int?)subjectDetails.Allow_prorated ?? 0;

                                    // Insert monthly fees installments if duration type is set
                                    if (durationSubType != 0 && noOfMonths > 0)
                                    {
                                        DateTime currentMonth = DateTime.Now;

                                        for (int month = 0; month < noOfMonths; month++)
                                        {
                                            DateTime feeMonth = currentMonth.AddMonths(month);
                                            double basicAmount = fees;

                                            // Handle prorated fees if enabled
                                            if (allowProrated == 1)
                                            {
                                                if (month == 0 || month == noOfMonths - 1)
                                                {
                                                    if (month == 0)
                                                    {
                                                        // First month prorated
                                                        DateTime monthStart = new DateTime(feeMonth.Year, feeMonth.Month, 1);
                                                        TimeSpan daysDiff = currentMonth.Subtract(monthStart);
                                                        basicAmount = Math.Round((30 - daysDiff.Days) * (fees / 30.0), 2);
                                                    }
                                                    else if (month == noOfMonths - 1 && courseEndDate.HasValue)
                                                    {
                                                        // Last month prorated
                                                        if (durationSubType == 3)
                                                        {
                                                            DateTime courseEndPlusOne = courseEndDate.Value.AddDays(1);
                                                            DateTime monthStart = new DateTime(feeMonth.Year, feeMonth.Month, 1);
                                                            TimeSpan daysDiff = courseEndPlusOne.Subtract(monthStart);
                                                            basicAmount = Math.Round(daysDiff.Days * fees / 30.0, 2);
                                                        }
                                                    }
                                                }
                                            }

                                            await db.ExecuteAsync(
                                                StudentQueries.InsertMonthlyFeesInstallment,
                                                new
                                                {
                                                    StudentId = studentId,
                                                    SubjectId = subjectId,
                                                    FeeMonth = feeMonth.Month,
                                                    FeeYear = feeMonth.Year,
                                                    BasicAmount = basicAmount,
                                                    BasicFees = basicAmount
                                                },
                                                transaction);
                                        }
                                    }
                                }
                            }
                        }
                    }
                }

                // Insert student batches
                if (request.BatchIds != null && request.BatchIds.Any())
                {
                    string studentName = $"{request.FirstName} {request.LastName}";
                    foreach (var batchId in request.BatchIds)
                    {
                        await db.ExecuteAsync(
                            StudentQueries.InsertStudentBatch,
                            new
                            {
                                StudentId = studentId,
                                BatchId = batchId,
                                InstId = instituteId,
                                StudentName = studentName,
                                BranchId = branchId
                            },
                            transaction);
                    }
                }

                // Insert student other fees with frequency logic
                if (!string.IsNullOrEmpty(request.OtherFeesIds))
                {
                    var otherFeesIds = request.OtherFeesIds.Split(',');
                    var existingOtherFees = await db.QueryAsync<int>(
                        StudentQueries.CheckExistingOtherFees,
                        new { StudentId = studentId },
                        transaction);

                    // Get student registration date for monthly fees calculation
                    var regDateResult = await db.QueryFirstOrDefaultAsync<DateTime>(
                        StudentQueries.GetStudentRegDate,
                        new { StudentId = studentId },
                        transaction);

                    foreach (var ofCodeStr in otherFeesIds)
                    {
                        if (int.TryParse(ofCodeStr.Trim(), out int ofCode))
                        {
                            // Check if other fee already exists
                            if (!existingOtherFees.Contains(ofCode))
                            {
                                var otherFeesDetails = await db.QueryFirstOrDefaultAsync<dynamic>(
                                    StudentQueries.GetOtherFeesDetails,
                                    new { OfCode = ofCode },
                                    transaction);

                                if (otherFeesDetails != null)
                                {
                                    int frequency = (int?)otherFeesDetails.of_Frequency ?? 0;
                                    decimal amount = otherFeesDetails.amount ?? 0;
                                    int isTaxable = otherFeesDetails.istaxable ? 1 : 0;
                                    int isIncluding = otherFeesDetails.isincluding ? 1 : 0;

                                    if (frequency == 2) // Monthly frequency
                                    {
                                        // Insert for all 12 months
                                        for (int month = 0; month <= 11; month++)
                                        {
                                            DateTime feeMonth = regDateResult.AddMonths(month).Date;

                                            await db.ExecuteAsync(
                                                StudentQueries.InsertStudentOtherFees,
                                                new
                                                {
                                                    StudentId = studentId,
                                                    OfCode = ofCode,
                                                    Amount = amount,
                                                    IsTaxable = isTaxable,
                                                    IsIncluding = isIncluding,
                                                    Months = feeMonth
                                                },
                                                transaction);
                                        }
                                    }
                                    else
                                    {
                                        // One-time fee
                                        await db.ExecuteAsync(
                                            StudentQueries.InsertStudentOtherFees,
                                            new
                                            {
                                                StudentId = studentId,
                                                OfCode = ofCode,
                                                Amount = amount,
                                                IsTaxable = isTaxable,
                                                IsIncluding = isIncluding,
                                                Months = (DateTime?)null
                                            },
                                            transaction);
                                    }
                                }
                            }
                        }
                    }
                }

                // Insert education details
                if (request.Education != null && request.Education.Any())
                {
                    foreach (var edu in request.Education)
                    {
                        await db.ExecuteAsync(
                            StudentQueries.InsertEducation,
                            new
                            {
                                StudentId = studentId,
                                Degree = edu.Degree.Replace("'", "''"),
                                College = edu.College?.Replace("'", "''"),
                                Stream = edu.Stream,
                                Percentage = edu.Percentage,
                                Year = edu.Year
                            },
                            transaction);
                    }
                }

                // Update student image separately
                if (request.Photo != null)
                {
                    await db.ExecuteAsync(
                        StudentQueries.UpdateStudentImage,
                        new
                        {
                            StudentId = studentId,
                            Photo = request.Photo
                        },
                        transaction);
                }

                transaction.Commit();

                // Update auto registration counter if registration number was auto-generated
                if (isAutoGenerated && tempRegNo.HasValue)
                {
                    int targetBranchId = regLevel == 0 ? 0 : branchId;
                    await db.ExecuteAsync(
                        StudentQueries.UpdateAutoRegCounter,
                        new { InstituteId = instituteId, BranchId = targetBranchId, NewCounter = tempRegNo.Value });
                }

                await SendRegistrationNotificationsAsync(db, instituteId, branchId, studentId, request, username, password, transaction);

                return (true, "Student registered successfully.", studentId, request.RegNo);
            }
            catch (Exception ex)
            {
                transaction.Rollback();
                return (false, $"Error registering student: {ex.Message}", null, null);
            }
        }

        public async Task<PagedResponse<StudentListDto>> SearchStudentsAsync(StudentSearchDto search, int instituteId)
        {
            using IDbConnection db = _dbFactory.CreateConnection();

            if (db.State == ConnectionState.Closed)
                db.Open();

            // Build SQL condition dynamically
            string sqlCondition = string.Empty;

            // Filter by ListType (Registration vs Enquiry)
            if (search.ListType == "Registration")
                sqlCondition += " AND registered = 'Yes'";
            else if (search.ListType == "Enquiry")
                sqlCondition += " AND registered = 'No'";

            // Name search
            if (!string.IsNullOrEmpty(search.StudentName))
            {
                string searchName = search.StudentName.Replace(" ", "").Replace("'", "''").Trim();
                sqlCondition += " AND (CONCAT_WS('',Salutation,fname, mname, lname) LIKE '%" + searchName + "%' OR CONCAT_WS('',Salutation,fname,lname) LIKE '%" + searchName + "%' OR CONCAT_WS('',Salutation,fname) LIKE '%" + searchName + "%' OR CONCAT_WS('', fname, mname, lname) LIKE '%" + searchName + "%' OR CONCAT_WS('',fname,lname) LIKE '%" + searchName + "%')";
            }

            // Apply filters only when values are provided
            //if (!string.IsNullOrEmpty(search.Reg))
            //    sqlCondition += " AND registered = '" + search.Reg + "'";
            if (!string.IsNullOrEmpty(search.RegManual))
                sqlCondition += " AND (RegNo_Manual='" + search.RegManual + "')";
            if (!string.IsNullOrEmpty(search.Phone))
                sqlCondition += " AND pcontact LIKE '" + search.Phone + "'";
            if (!string.IsNullOrEmpty(search.Email))
                sqlCondition += " AND EmailId LIKE '%" + search.Email + "%'";
            if (search.Status != 2)
                sqlCondition += " AND v.StatusFlag = " + search.Status;
            if (search.CurriculumId != 0)
            {
                sqlCondition += @"
        AND EXISTS (
            SELECT 1
            FROM student_course sc_curr
            INNER JOIN tbl_course tc_curr
                ON tc_curr.courseID = sc_curr.CourseID
            WHERE sc_curr.StudID = v.RegNo
              AND tc_curr.CrclmId = " + search.CurriculumId + @"
        )";
            }
            if (search.CourseId != 0)
                sqlCondition += " AND ts.courseid=" + search.CourseId;
            if (search.SubId != 0)
                sqlCondition += " AND s.subjectid=" + search.SubId;
            if (search.BatchId != 0)
                sqlCondition += " AND b.batchid=" + search.BatchId;
            if (search.EnquiryStatus != 0)
                sqlCondition += " AND v.EnqStatus=" + search.EnquiryStatus;

            // Date range filter
            if (!string.IsNullOrEmpty(search.RegFrDate) && !string.IsNullOrEmpty(search.RegToDate))
            {
                DateTime? frDate = null;
                DateTime? toDate = null;
                if (DateTime.TryParse(search.RegFrDate, out DateTime parsedFr))
                    frDate = parsedFr;
                if (DateTime.TryParse(search.RegToDate, out DateTime parsedTo))
                    toDate = parsedTo;

                if (frDate.HasValue && toDate.HasValue)
                {
                    if (search.ListType == "Registration")
                        sqlCondition += " AND (DATE_FORMAT(v.regdate,'%Y-%m-%d') BETWEEN '" + frDate.Value.ToString("yyyy-MM-dd") + "' AND '" + toDate.Value.ToString("yyyy-MM-dd") + "') ";
                    else if (search.ListType == "Enquiry")
                        sqlCondition += " AND (DATE_FORMAT(enquirydate,'%Y-%m-%d') BETWEEN '" + frDate.Value.ToString("yyyy-MM-dd") + "' AND '" + toDate.Value.ToString("yyyy-MM-dd") + "') AND registered='no'";
                    else
                        sqlCondition += " AND ((DATE_FORMAT(v.regdate,'%Y-%m-%d') BETWEEN '" + frDate.Value.ToString("yyyy-MM-dd") + "' AND '" + toDate.Value.ToString("yyyy-MM-dd") + "') OR (DATE_FORMAT(enquirydate,'%Y-%m-%d') BETWEEN '" + frDate.Value.ToString("yyyy-MM-dd") + "' AND '" + toDate.Value.ToString("yyyy-MM-dd") + "')) AND registered IN('yes','no')";
                }
            }

            if (search.NotInBatch)
                sqlCondition += " AND v.RegNo NOT IN (SELECT sb.studentid FROM studentbatch sb WHERE sb.branchid=" + search.BranchId + " AND sb.instituteid=" + instituteId + ")";

            // Sorting
            string direction = "ASC";
            if (!string.IsNullOrEmpty(search.SortDirection) && search.SortDirection.Equals("desc", StringComparison.OrdinalIgnoreCase))
                direction = "DESC";

            string orderByClause;

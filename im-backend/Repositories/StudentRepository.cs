        private async Task<int> GetNextAvailableManualRegNoAsync(
    IDbConnection db,
    int branchId,
    string regId = "0")
        {
            // Get the latest registration number.
            int lastRegNo =
                await db.ExecuteScalarAsync<int?>(
                    StudentQueries.GetLastRegNo) ?? 0;

            // Start from the next number.
            int nextRegNo = lastRegNo + 1;

            // Find the first number not already used as a manual
            // registration number for this branch.
            while (true)
            {
                int duplicateCount =
                    await db.ExecuteScalarAsync<int>(
                        StudentQueries.CheckDuplicateRegNo,
                        new
                        {
                            RegNo = nextRegNo.ToString(),
                            BranchId = branchId,
                            RegId = regId
                        });

                if (duplicateCount == 0)
                    return nextRegNo;

                nextRegNo++;

                if (nextRegNo == int.MaxValue)
                {
                    throw new InvalidOperationException(
                        "Unable to generate a registration number.");
                }
            }
        }

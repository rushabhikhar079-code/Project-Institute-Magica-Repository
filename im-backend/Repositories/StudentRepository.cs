            using IDbConnection db = _dbFactory.CreateConnection();
            if (db.State == ConnectionState.Closed)
                db.Open();

            var conditions = new List<string>();
            var parameters = new DynamicParameters();
            parameters.Add("InstituteId", instituteId);
            parameters.Add("BranchId", branchId);

            // Add enquiry allocate join if userId is provided
            string enquiryAllocateJoin = "";
            if (!string.IsNullOrEmpty(userId))
            {
                enquiryAllocateJoin = " LEFT JOIN enquiryallocate ea ON ea.regno=r.regno AND ea.user_id = @UserId";
                parameters.Add("UserId", userId);

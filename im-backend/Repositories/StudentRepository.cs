        public async Task<(bool Success, string Message, int? StudentId)> RegisterEnquiryAsync(StudentEnquiryDto request, int instituteId, int branchId, int userId, string ipAddress, string userRole = "")
        {
            using IDbConnection db = _dbFactory.CreateConnection();
            if (db.State == ConnectionState.Closed)
                db.Open();
            using var transaction = db.BeginTransaction();

            try
            {
                // Delete temp education records before registration
                await db.ExecuteAsync(StudentQueries.DeleteTempEducation, transaction: transaction);

                // Date validation: Registration date cannot be future date (as per legacy)
                DateTime? regDate = null;

                if (!string.IsNullOrWhiteSpace(request.RegDate))
                {
                    regDate = DateTime.Parse(request.RegDate);

                    TimeSpan ts = DateTime.Now - regDate.Value;

                    if (ts.TotalDays < 0)
                    {
                        return (false, "Registration Date cannot be future date", null);
                    }
                }

                // Date validation: Follow-up date validation
                if (request.EnableFollowUp && !string.IsNullOrEmpty(request.FollowUpDate))
                {
                    DateTime followUpDate = DateTime.Parse(request.FollowUpDate);
                    // If follow-up status is not "Call Back" and requires future date, check it's not past
                    if (request.FollowUpStatusId.HasValue)
                    {
                        // TODO: Get follow-up status details to check if it requires future date
                        // For now, basic validation
                        if (followUpDate < DateTime.Today)
                        {
                            return (false, "Follow-up date cannot be in the past", null);
                        }
                    }
                }

                // Date validation: DOB must be less than today
                DateTime? dob = null;
                if (!string.IsNullOrEmpty(request.DateOfBirth))
                {
                    dob = DateTime.Parse(request.DateOfBirth);
                    if (dob >= DateTime.Today)
                    {
                        return (false, "Date of birth must be less than today's date", null);
                    }
                }

                // Image size validation: must be <= 2MB
                if (request.Photo != null && request.Photo.Length > 2097152)
                {
                    return (false, "Please select image file up to 2MB", null);
                }

                // Check for duplicate student

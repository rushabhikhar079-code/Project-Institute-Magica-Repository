        public async Task<(bool Success, string Message)> AllocateEnquiryAsync(EnquiryAllocationSubmitDto request, int instituteId)
        {
            using IDbConnection db = _dbFactory.CreateConnection();
            if (db.State == ConnectionState.Closed)
                db.Open();

            try
            {
                // Validate inputs
                if (string.IsNullOrEmpty(request.StudentIds))
                    return (false, "Please select at least one student.");

                if (string.IsNullOrEmpty(request.UserId))
                    return (false, "User ID is required.");

                // Delete existing allocations for the given student IDs
                string deleteQuery = string.Format(StudentQueries.DeleteEnquiryAllocation, request.StudentIds);
                await db.ExecuteAsync(deleteQuery);

                // Get current time in India Standard Time
                DateTime indiaTime = TimeZoneInfo.ConvertTimeBySystemTimeZoneId(DateTime.Now, TimeZone.CurrentTimeZone.StandardName, "India Standard Time");
                string alctdate = indiaTime.ToString("yyyy-MM-dd HH:mm:ss");

                // Insert new allocations for each student ID
                char[] separator = new char[] { ',' };
                foreach (string studId in request.StudentIds.Split(separator))
                {
                    if (!string.IsNullOrEmpty(studId))
                    {
                        string insertQuery = string.Format(StudentQueries.InsertEnquiryAllocation, studId, request.UserId, alctdate);
                        await db.ExecuteAsync(insertQuery);
                    }
                }

                // Get user details for email notification
                var userDetails = await db.QueryFirstOrDefaultAsync(
                    StudentQueries.GetUserById,
                    new { InstituteId = instituteId, BranchId = request.BranchId, UserId = request.UserId });
                string userName = userDetails?.Username ?? "User";

                // Send email notification
                await _emailService.SendEnquiryAllocationEmailAsync(db, instituteId, request.BranchId, request.UserId, userName);

                return (true, "Enquiries allocated to selected user successfully.");
            }
            catch (Exception ex)
            {
                return (false, $"Problem in enquiry allocation: {ex.Message}");
            }
        }
